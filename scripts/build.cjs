'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
let source = fs.readFileSync(path.join(root, 'zhihu-long-image.user.js'), 'utf8');
const version = require('../package.json').version;
const repository = JSON.parse(fs.readFileSync(path.join(root, 'release-config.json'), 'utf8')).repository;
if (repository && !/^[A-Za-z0-9][A-Za-z0-9-]*\/[A-Za-z0-9_.-]+$/.test(repository)) throw new Error('release-config仓库名无效。');
const homepage = repository ? `https://github.com/${repository}` : '';
const release = homepage ? `${homepage}/releases/latest` : '';
if (repository) {
  source = source.replace(/^\/\/ @(?:homepageURL|supportURL|updateURL|downloadURL)\s+.*\r?\n/gm, '');
  source = source.replace('// ==/UserScript==', [
    `// @homepageURL  ${homepage}`,
    `// @supportURL   ${homepage}/issues`,
    `// @updateURL    ${release}/download/zhihu-long-image.meta.js`,
    `// @downloadURL  ${release}/download/zhihu-long-image.user.js`,
    '// ==/UserScript==',
  ].join('\n'));
  fs.writeFileSync(path.join(root, 'zhihu-long-image.user.js'), source);
}
if (!source.includes(`// @version      ${version}`)) throw new Error('油猴脚本版本和 package.json 不一致。');
const manifestPath = path.join(root, 'extension', 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (manifest.version !== version) throw new Error('扩展版本不一致。');
if (homepage) manifest.homepage_url = homepage;
else delete manifest.homepage_url;
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'extension/release-info.json'), JSON.stringify({ version, repository, homepage, release }, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'docs/install-config.js'), `/* Generated at build time. */\nglobalThis.ZLI_INSTALL = ${JSON.stringify({ version, repository })};\n`);
for (const name of ['install.css', 'install.js', 'install-config.js']) fs.copyFileSync(path.join(root, 'docs', name), path.join(root, 'extension', name));
const installPage = fs.readFileSync(path.join(root, 'docs/install.html'), 'utf8').replace('href="../PRIVACY.md"', 'href="PRIVACY.md"').replace('href="../LICENSE"', 'href="LICENSE"');
fs.writeFileSync(path.join(root, 'extension/install.html'), installPage);
for (const name of ['PRIVACY.md', 'LICENSE']) fs.copyFileSync(path.join(root, name), path.join(root, 'extension', name));
const vendor = fs.readFileSync(path.join(root, 'extension/vendor/html2canvas.min.js'));
const hash = crypto.createHash('sha256').update(vendor).digest('hex');
if (hash !== 'e87e550794322e574a1fda0c1549a3c70dae5a93d9113417a429016838eab8cb') throw new Error('html2canvas 文件哈希校验失败。');
const pdfHash = crypto.createHash('sha256').update(fs.readFileSync(path.join(root, 'extension/vendor/jspdf.umd.min.js'))).digest('hex');
if (pdfHash !== 'e6551fcdc32f09d6853b2c5126d18d01d9447e0da618a41a11ebeee0f6c20d54') throw new Error('jsPDF文件哈希校验失败。');
let core = source.replace(/^\/\/ ==UserScript==[\s\S]*?^\/\/ ==\/UserScript==\s*/m, '');
core = core.replace("(() => {\n  'use strict';", "(async () => {\n  'use strict';\n  await globalThis.ZLI_READY;");
fs.writeFileSync(path.join(root, 'extension/core.js'), `/* Generated by scripts/build.cjs from zhihu-long-image.user.js. jasonLi · MIT. */\n${core}`);

// 本地生成不依赖图片工具的 PNG 图标；图形为蓝底白色长文页。
const zlib = require('node:zlib');
function chunk(type, data) {
  const out = Buffer.alloc(data.length + 12);
  out.writeUInt32BE(data.length, 0); out.write(type, 4); data.copy(out, 8);
  let crc = 0xffffffff;
  for (const byte of out.subarray(4, out.length - 4)) {
    crc ^= byte;
    for (let k = 0; k < 8; k++) crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
  }
  out.writeUInt32BE((crc ^ 0xffffffff) >>> 0, out.length - 4);
  return out;
}
fs.mkdirSync(path.join(root, 'extension/icons'), { recursive: true });
for (const size of [16, 48, 128]) {
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const offset = y * (size * 4 + 1) + 1 + x * 4;
    const nx = x / size, ny = y / size;
    const sheet = nx > .24 && nx < .76 && ny > .13 && ny < .87;
    const line = nx > .34 && nx < .66 && [.30, .43, .56, .69].some(v => ny > v && ny < v + .045);
    const color = sheet && !line ? [255, 255, 255] : [5, 105, 223];
    raw.set([...color, 255], offset);
  }
  const header = Buffer.alloc(13); header.writeUInt32BE(size, 0); header.writeUInt32BE(size, 4); header[8] = 8; header[9] = 6;
  fs.writeFileSync(path.join(root, `extension/icons/icon${size}.png`), Buffer.concat([
    Buffer.from('89504e470d0a1a0a', 'hex'), chunk('IHDR', header), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0)),
  ]));
}
console.log(`Built extension v${version}; bundled html2canvas SHA-256 verified.`);
